#!/bin/bash
# Keeps the Solas worker running with macOS launchd (M6C). Opt-in: nothing
# here runs until you call `install`. See docs/worker-launchd.md.
#
#   scripts/launchd/solas-worker.sh install     write the LaunchAgent and start it
#   scripts/launchd/solas-worker.sh start       start it (or start it again after `stop`)
#   scripts/launchd/solas-worker.sh stop        stop it gracefully until `start` or next login
#   scripts/launchd/solas-worker.sh restart     stop and start again
#   scripts/launchd/solas-worker.sh status      is it loaded, its PID and last exit code
#   scripts/launchd/solas-worker.sh logs [-f]   the last lines of its logs (-f follows)
#   scripts/launchd/solas-worker.sh uninstall   stop it and remove the LaunchAgent
#
# Runs as you, never with sudo. The generated plist holds paths only: the
# worker reads its secrets from .env.local itself when it starts (node
# --env-file), so no secret is copied into the plist or printed here.
#
# For testing a second, separate copy (another label, another env file):
#   SOLAS_LAUNCHD_LABEL=local.solas.worker-test SOLAS_ENV_FILE=/path/to/test.env scripts/launchd/solas-worker.sh install

set -euo pipefail

die() { echo "solas-worker: $*" >&2; exit 1; }

[ "$(uname -s)" = "Darwin" ] || die "launchd is macOS only."
[ "$(id -u)" -ne 0 ] || die "run this as yourself, not with sudo: the worker must run as your user."

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
LABEL="${SOLAS_LAUNCHD_LABEL:-local.solas.worker}"
[[ "$LABEL" =~ ^[A-Za-z0-9.-]+$ ]] || die "SOLAS_LAUNCHD_LABEL may only contain letters, digits, dots, and dashes."
ENV_FILE="${SOLAS_ENV_FILE:-$PROJECT_DIR/.env.local}"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LOG_DIR="$HOME/Library/Logs/Solas"
OUT_LOG="$LOG_DIR/$LABEL.log"
ERR_LOG="$LOG_DIR/$LABEL.error.log"
DOMAIN="gui/$(id -u)"
SERVICE="$DOMAIN/$LABEL"

is_loaded() { launchctl print "$SERVICE" >/dev/null 2>&1; }

# Paths go into XML: escape the five special characters.
xml() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e 's/"/\&quot;/g' -e "s/'/\&apos;/g"; }

install() {
  # Resolved now, from your terminal: launchd starts without your shell's PATH.
  local node
  node="$(command -v node)" || die "node isn't on your PATH. Install Node.js 24 first."
  [ -f "$PROJECT_DIR/node_modules/tsx/package.json" ] || die "dependencies are missing. Run npm install in $PROJECT_DIR first."
  [ -f "$ENV_FILE" ] || die "$ENV_FILE doesn't exist. Copy .env.example to .env.local and fill it in."
  case "$ENV_FILE" in /*) ;; *) die "SOLAS_ENV_FILE must be an absolute path." ;; esac

  mkdir -p "$HOME/Library/LaunchAgents" "$LOG_DIR"
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/launchd/solas-worker.sh. Paths only, no secrets. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$(xml "$LABEL")</string>
  <key>ProgramArguments</key>
  <array>
    <string>$(xml "$node")</string>
    <string>--import</string>
    <string>tsx</string>
    <string>--conditions=react-server</string>
    <string>--env-file=$(xml "$ENV_FILE")</string>
    <string>src/worker/index.mts</string>
  </array>
  <key>WorkingDirectory</key>
  <string>$(xml "$PROJECT_DIR")</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>$(xml "$(dirname "$node")"):/usr/bin:/bin:/usr/sbin:/sbin</string>
    <key>HOME</key>
    <string>$(xml "$HOME")</string>
  </dict>
  <!-- Start when loaded: at install, and at every login. -->
  <key>RunAtLoad</key>
  <true/>
  <!-- Restart only after an unexpected exit (crash, kill, non-zero code); a graceful stop exits 0 and stays stopped. -->
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <!-- At most one start every 30 seconds, so a worker that keeps crashing can't spin. -->
  <key>ThrottleInterval</key>
  <integer>30</integer>
  <!-- After SIGTERM, time to stop runs and record them before launchd sends SIGKILL. -->
  <key>ExitTimeOut</key>
  <integer>30</integer>
  <key>StandardOutPath</key>
  <string>$(xml "$OUT_LOG")</string>
  <key>StandardErrorPath</key>
  <string>$(xml "$ERR_LOG")</string>
</dict>
</plist>
PLIST
  plutil -lint "$tmp" >/dev/null || { rm -f "$tmp"; die "generated an invalid plist."; }

  if is_loaded; then launchctl bootout "$SERVICE" 2>/dev/null || true; fi
  mv "$tmp" "$PLIST"
  chmod 644 "$PLIST"
  launchctl bootstrap "$DOMAIN" "$PLIST"
  echo "Installed $LABEL and started it."
  echo "  LaunchAgent: $PLIST"
  echo "  Node:        $node (run install again after changing Node versions)"
  echo "  Logs:        $OUT_LOG"
  echo "It starts again at every login. Check it with: $0 status"
}

start() {
  [ -f "$PLIST" ] || die "not installed. Run: $0 install"
  if is_loaded; then
    launchctl kickstart "$SERVICE"
  else
    launchctl bootstrap "$DOMAIN" "$PLIST"
  fi
  echo "Started $LABEL."
}

stop() {
  if is_loaded; then
    # bootout sends SIGTERM (the worker stops its runs and records them) and unloads the job,
    # so KeepAlive doesn't start it again. It is loaded again at the next login.
    launchctl bootout "$SERVICE" 2>/dev/null || true
    echo "Stopped $LABEL. It starts again at your next login, or with: $0 start"
  else
    echo "$LABEL isn't running under launchd."
  fi
}

status() {
  if [ ! -f "$PLIST" ]; then
    echo "$LABEL: not installed (autostart is off)."
    return
  fi
  if ! is_loaded; then
    echo "$LABEL: installed, not loaded (stopped; it loads again at next login)."
    return
  fi
  echo "$LABEL: loaded"
  launchctl print "$SERVICE" | grep -E '^\s*(state|pid|runs|last exit code|last terminating signal) =' | sed 's/^[[:space:]]*/  /'
  echo "Worker health as Solas sees it: Settings → Worker."
}

logs() {
  [ -f "$OUT_LOG" ] || [ -f "$ERR_LOG" ] || die "no logs yet in $LOG_DIR."
  if [ "${1:-}" = "-f" ]; then
    tail -n 20 -f "$OUT_LOG" "$ERR_LOG"
  else
    tail -n 50 "$OUT_LOG" "$ERR_LOG" 2>/dev/null
  fi
}

uninstall() {
  if is_loaded; then launchctl bootout "$SERVICE" 2>/dev/null || true; fi
  rm -f "$PLIST"
  echo "Removed $LABEL. The worker no longer starts by itself."
  echo "Kept: your database, agent workspaces, .env.local, and the logs in $LOG_DIR."
}

case "${1:-}" in
  install) install ;;
  start) start ;;
  stop) stop ;;
  restart)
    # kickstart -k sends SIGTERM, waits for the exit, and starts it again.
    if is_loaded; then launchctl kickstart -k "$SERVICE" && echo "Restarted $LABEL."; else start; fi ;;
  status) status ;;
  logs) logs "${2:-}" ;;
  uninstall) uninstall ;;
  *) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
